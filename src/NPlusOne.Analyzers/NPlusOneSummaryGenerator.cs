using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using NPlusOne.Analyzers.Analysis;
using NPlusOne.Analyzers.Model;

namespace NPlusOne.Analyzers;

/// <summary>
/// Writes this project's method summaries into its assembly, so that projects referencing it can
/// follow calls into it: which public methods run a query (always, or when an argument is an EF
/// query) or save, what they return, which navigations they read, which delegates they call per
/// element, and which navigations the model auto-includes. It runs in builds only
/// (<c>RegisterImplementationSourceOutput</c>), never on keystrokes in the IDE, and only in projects
/// that reference EF Core. Set the MSBuild property <c>NPlusOneEmitSummaries</c> to <c>false</c> to turn it off.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class NPlusOneSummaryGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
        => context.RegisterImplementationSourceOutput(
            context.CompilationProvider.Combine(context.AnalyzerConfigOptionsProvider),
            static (output, input) => EmitSafely(output, input.Left, input.Right));

    /// <summary>
    /// Runs <see cref="Emit"/>, and adds nothing when it fails: a generator that throws is reported as warning CS8785,
    /// which breaks every build that treats warnings as errors. Without summaries the referencing projects only see
    /// less, they never see wrong facts.
    /// </summary>
    /// <param name="output">Where the source goes.</param>
    /// <param name="compilation">The project's compilation.</param>
    /// <param name="options">The analyzer config options, with the MSBuild property.</param>
    private static void EmitSafely(SourceProductionContext output, Compilation compilation, AnalyzerConfigOptionsProvider options)
    {
        try
        {
            Emit(output, compilation, options);
        }
        catch (OperationCanceledException)
        {
            throw;
        }
#pragma warning disable CA1031 // A failed summary must not fail the user's build.
        catch (Exception)
#pragma warning restore CA1031
        {
        }
    }

    /// <summary>Computes the summaries and adds them as assembly attributes.</summary>
    /// <param name="output">Where the source goes.</param>
    /// <param name="compilation">The project's compilation.</param>
    /// <param name="options">The analyzer config options, with the MSBuild property.</param>
    private static void Emit(SourceProductionContext output, Compilation compilation, AnalyzerConfigOptionsProvider options)
    {
        if (options.GlobalOptions.TryGetValue("build_property.NPlusOneEmitSummaries", out var enabled)
            && string.Equals(enabled.Trim(), "false", StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        var settings = Settings.Read(options, compilation);
        if (KnownSymbols.TryCreate(compilation, settings) is not { } symbols)
        {
            return;
        }

        var session = new Session(compilation, symbols, settings);
        var attribute = $"NPlusOneSummary{Suffix(compilation.AssemblyName ?? "")}Attribute";
        var source = new StringBuilder("// <auto-generated/>\n// N+1 analyzer summaries for the projects that reference this one.\n");
        Append(source, attribute, "", ReferencedSummaries.CompleteMarker);

        foreach (var type in session.SourceTypes)
        {
            foreach (var member in type.GetMembers())
            {
                output.CancellationToken.ThrowIfCancellationRequested();
                if (member is not IMethodSymbol { IsImplicitlyDeclared: false } method
                    || method.MethodKind is not (MethodKind.Ordinary or MethodKind.PropertyGet or MethodKind.ExplicitInterfaceImplementation)
                    || (method.DeclaredAccessibility == Accessibility.Private && method.MethodKind != MethodKind.ExplicitInterfaceImplementation)
                    || DocumentationCommentId.CreateDeclarationId(method) is not { } id
                    || SummaryExport.Encode(session, method) is not { } facts)
                {
                    continue;
                }

                Append(source, attribute, id, facts);
            }
        }

        foreach (var property in session.Entities.OwnAutoIncludes)
        {
            if (DocumentationCommentId.CreateDeclarationId(property) is { } id)
            {
                Append(source, attribute, id, ReferencedSummaries.AutoIncludeMarker);
            }
        }

        source.Append("\nnamespace ").Append(ReferencedSummaries.AttributeNamespace).Append("\n{\n")
            .Append("    [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = true)]\n")
            .Append("    internal sealed class ").Append(attribute).Append(" : global::System.Attribute\n    {\n")
            .Append("        public ").Append(attribute).Append("(string member, string facts) { }\n    }\n}\n");
        output.AddSource("NPlusOne.Summaries.g.cs", source.ToString());
    }

    /// <summary>Appends one assembly attribute.</summary>
    /// <param name="source">The source being built.</param>
    /// <param name="attribute">The attribute class name.</param>
    /// <param name="member">The documentation id, or empty for the completeness marker.</param>
    /// <param name="facts">The facts.</param>
    private static void Append(StringBuilder source, string attribute, string member, string facts)
        => source.Append("[assembly: global::").Append(ReferencedSummaries.AttributeNamespace).Append('.').Append(attribute).Append('(')
            .Append(SymbolDisplay.FormatLiteral(member, quote: true)).Append(", ")
            .Append(SymbolDisplay.FormatLiteral(facts, quote: true)).Append(")]\n");

    /// <summary>
    /// A suffix that makes the attribute class unique per assembly: with <c>InternalsVisibleTo</c>, a
    /// test project sees the tested project's internal attribute, and two classes of the same name would
    /// conflict (CS0436).
    /// </summary>
    /// <param name="assemblyName">The assembly name.</param>
    private static string Suffix(string assemblyName)
    {
        // FNV-1a: stable across processes, unlike string.GetHashCode.
        var hash = 2166136261u;
        foreach (var c in assemblyName)
        {
            hash = (hash ^ c) * 16777619u;
        }

        return hash.ToString("x8", System.Globalization.CultureInfo.InvariantCulture);
    }
}
